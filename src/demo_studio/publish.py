from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def create_publication_draft(
    run_dir: Path,
    *,
    platform: str = "youtube",
    title: str | None = None,
    description: str | None = None,
) -> dict[str, Any]:
    """Dry-run publication draft (Phase 5). Never uploads."""
    run_dir = Path(run_dir)
    demo = run_dir / "demo.mp4"
    if not demo.is_file():
        raise FileNotFoundError(f"missing {demo}")
    publish_md = None
    for candidate in (
        Path("demos/astro-cms/PUBLISH.md"),
        run_dir.parents[1] / "demos/astro-cms/PUBLISH.md",
    ):
        if candidate.is_file():
            publish_md = candidate.read_text(encoding="utf-8")
            break
    draft = {
        "platform": platform,
        "dry_run": True,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "media": str(demo.resolve()),
        "captions": str((run_dir / "captions.vtt").resolve()) if (run_dir / "captions.vtt").is_file() else None,
        "title": title or "WordPress → self-hosted EmDash (demo-studio)",
        "description": description
        or (publish_md.split("## Description", 1)[-1].strip() if publish_md else ""),
        "status": "draft",
        "upload": {"attempted": False, "reason": "dry-run only; set DEMO_STUDIO_ALLOW_UPLOAD=1 in a future slice"},
    }
    path = run_dir / f"publication-{platform}-draft.json"
    path.write_text(json.dumps(draft, indent=2) + "\n", encoding="utf-8")
    draft["path"] = str(path)
    return draft


def prepare_x_publication_dry_run(run_dir: Path, text: str | None = None) -> dict[str, Any]:
    draft = create_publication_draft(
        run_dir,
        platform="x",
        title=None,
        description=text
        or "Product walkthrough generated by demo-studio (dry-run — not posted).",
    )
    draft["x"] = {
        "media_attached": True,
        "text_chars": len(draft.get("description") or ""),
        "would_call": "POST media/upload + statuses/update (not executed)",
    }
    path = Path(draft["path"])
    path.write_text(json.dumps(draft, indent=2) + "\n", encoding="utf-8")
    return draft
